export const ROLES = ['employee', 'supervisor', 'admin'] as const;

export type Role = (typeof ROLES)[number];

/** Higher rank implies every permission of the lower ranks. */
export const ROLE_RANK: Record<Role, number> = {
  employee: 1,
  supervisor: 2,
  admin: 3,
};

export function isRole(value: unknown): value is Role {
  return typeof value === 'string' && (ROLES as readonly string[]).includes(value);
}

export interface UserProfile {
  uid: string;
  name: string;
  email: string;
  role: Role;
  createdAt: string | null;
  updatedAt: string | null;
}

/** Identity extracted from a verified Firebase ID token. */
export interface TokenIdentity {
  uid: string;
  email: string | null;
  name: string | null;
}

export interface AuthenticatedUser {
  uid: string;
  email: string;
  name: string;
  role: Role;
}

export interface Product {
  barcode: string;
  name: string;
  imageUrl: string | null;
  brand: string | null;
  category: string | null;
  quantityLabel: string | null;
  updatedAt: string | null;
}

export interface Stock {
  barcode: string;
  quantity: number;
  updatedAt: string | null;
}

export interface ProductWithStock extends Product {
  stock: Stock | null;
}

export interface LowStockItem extends ProductWithStock {
  stock: Stock;
}

export interface StatisticsEntry {
  barcode: string;
  views: number;
}

export interface StockSummary {
  totalProducts: number;
  totalUnits: number;
  lowStockCount: number;
  outOfStockCount: number;
  lowStockThreshold: number;
}

export interface Dashboard {
  summary: StockSummary;
  topViewed: ProductWithStock[];
  lowStock: LowStockItem[] | null;
}

export interface CreateUserInput {
  name: string;
  email: string;
  role: Role;
}

export interface ProvisionUserInput extends CreateUserInput {
  /** One-time password generated by the backend; never exposed to clients. */
  temporaryPassword: string;
}

export interface CreatedUser {
  profile: UserProfile;
  /** Null when Firebase could not generate the reset link; the user still exists. */
  passwordResetLink: string | null;
}
